"""Prepare a labelled synthetic three-activation test using the frozen 50-company universe."""
import argparse
from datetime import date, timedelta
from pathlib import Path

from research_benchmarks.longitudinal import load_scenario, run_campaign
from research_agent.simulation.state import save
import yaml


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--run", action="store_true", help="Call the configured LLM and temporally bounded Tavily")
    args = parser.parse_args()
    config = load_scenario(Path("benchmarks/colaboracion-historica-v1/scenario.yaml"))
    config.update(id="smoke-longitudinal-controlado", end="2023-03-31")
    symbol = config["universe"][0]["symbol"]
    config["price_review"] = {"status": "approved", "basis": "synthetic", "evidence": "Constant synthetic prices generated by scripts/longitudinal_smoke.py; no corporate actions"}
    config["messages"] = {
        "2023-01-01": f"Prueba de integración con datos financieros SINTÉTICOS, sin conclusiones de inversión. Consulta la cartera y los fundamentales de {symbol}, realiza una búsqueda web breve acotada a la fecha simulada para comprobar el acceso, solicita una compra ficticia de 100 USD de {symbol} y conserva en indice.md la referencia a una nota con la etiqueta continuidad-smoke-v1. Distingue las fuentes web reales de las cifras ficticias.",
        "2023-03-01": f"Continúa la prueba de integración SINTÉTICA. Recupera la nota continuidad-smoke-v1 sin inventar su contenido, consulta la cartera y su historial, y solicita cerrar la posición {symbol} si permanece abierta. Explica qué comprobaste y qué no. No extraigas conclusiones de inversión."}
    prices = []
    current = date(2022, 12, 26)
    while current <= date(2023, 3, 31):
        if current.weekday() < 5:
            prices.extend({"symbol": c["symbol"], "date": str(current), "close": "10", "provider": "synthetic"}
                          for c in config["universe"])
        current += timedelta(days=1)
    facts = [{"symbol": c["symbol"], "metric": "total_revenue", "definition": "Ingresos ficticios",
              "value": "1000000", "unit": "currency", "currency": "USD", "period": "2021-12-31",
              "period_type": "annual", "published_at": None, "source_ref": f"synthetic:{c['symbol']}:2021:revenue",
              "provenance": {"provider": "synthetic", "payload_hash": "synthetic-fixture-v1"}}
             for c in config["universe"]]
    data = {"schema_version": "historical-input-v1", "price_basis": "synthetic", "prices": prices, "facts": facts,
            "limitations": ["SYNTHETIC integration fixture; no historical financial inference is valid."]}
    args.output.mkdir(parents=True, exist_ok=False)
    definition = args.output / "scenario.yaml"
    definition.write_text(yaml.safe_dump(config, allow_unicode=True, sort_keys=False), encoding="utf-8")
    save(args.output / "data.json", data)
    if args.run:
        raise SystemExit(run_campaign(args.output / "campaign", scenario=definition, data=data))
    print(args.output)


if __name__ == "__main__":
    main()
